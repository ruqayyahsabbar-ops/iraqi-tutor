import streamlit as st

# إعدادات الصفحة الأساسية
st.set_page_config(
    page_title="مساعد المنهج العراقي الوزاري",
    page_icon="📚",
    layout="centered"
)

# عنوان التطبيق الموجه للطلاب
st.title("📚 مساعد المنهج العراقي الوزاري")
st.write("أهلاً بك عزيزي الطالب! اكتب سؤالك أو الموضوع الذي تبحث عنه لتحصل على الإجابة الحرفية المعتمدة من وزارة التربية.")

st.divider()

# الشريط الجانبي لاختيار المرحلة والمادة فقط (بدون رفع ملفات للطلاب)
st.sidebar.header("🎯 تحديد المنهج")

grade = st.sidebar.selectbox(
    "المرحلة الدراسية:",
    ["السادس الإعدادي", "الخامس الإعدادي"]
)

subject = st.sidebar.selectbox(
    "المادة الدراسية:",
    [
        "الفيزياء", 
        "الكيمياء", 
        "الأحياء", 
        "الرياضيات", 
        "اللغة العربية", 
        "اللغة الإنجليزية", 
        "التربية الإسلامية"
    ]
)

st.sidebar.divider()
st.sidebar.info("💡 جميع الإجابات مطابقة حصراً للكتب المدرسية الرسمية والأجوبة الوزارية.")

# حقل إدخال السؤال أو الموضوع
user_question = st.text_input(
    f"✍️ اكتب سؤالك أو العنوان في مادة ({subject}):",
    placeholder="مثال: قانون أوم، الاستثناء، التبرعم، ثرموديناميك..."
)

# زر البحث
if st.button("🚀 ابحث عن الإجابة الوزارية", type="primary"):
    if not user_question.strip():
        st.warning("⚠️ الرجاء كتابة السؤال أو الموضوع أولاً.")
    else:
        with st.spinner("⏳ جاري استخراج النص الوزاري الدقيق..."):
            
            # عرض الإجابة الحرفية مباشرة حسب المادة والسؤال
            st.success(f"✅ الإجابة المعتمدة لمادة ({subject} - {grade}):")
            
            # هنا يمكنكِ لاحقاً ربط الأسئلة بملفات الكتب المخزنة في النظام
            st.markdown(f"""
            ### الموضوع: {user_question}
            
            * **النص الحرفي من المنهج:** يعتمد هذا السؤال على الصيغة الرسمية الواردة في طبعة كتاب {subject} للصف {grade} المعتمدة من قبل المديرية العامة للتحضير والتعليم.
            * **النقاط والخطوات النموذجية للوزاري:**
              1. **التعريف / القانون الأساسي:** يكتب الطالب القانون أو النص العلمي بدقة دون أي نقص لضمان الدرجة كاملة.
              2. **التوضيح العلمي:** التفاصيل والرسوم أو الإعراب التفصيلي (حسب المادة) كما وردت في أفرع الإحيائي والتطبيقي والأدبي.
              3. **ملاحظة مركز الفحص:** يُحاسب الطالب على ذكر الوحدات الدراسية والتعاليل المرتبطة بالسبب العلمي حصراً.
            """)

st.divider()
st.markdown("<p style='text-align: center; color: gray;'>منصة المنهج العراقي التعليمية 💡</p>", unsafe_order_html=True)
    
