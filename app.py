import streamlit as st

# إعدادات الصفحة الأساسية
st.set_page_config(
    page_title="مساعد المنهج العراقي الوزاري",
    page_icon="📚",
    layout="centered"
)

# عنوان التطبيق الموجه للطلاب
st.title("📚 مساعد المنهج العراقي الوزاري الشامل")
st.write("أهلاً بك عزيزي الطالب! اختر مرحلتك الدراسية ومادتك، واكتب سؤالك لتحصل على الإجابة الحرفية المعتمدة.")

st.divider()

# الشريط الجانبي لاختيار المراحل الدراسية والمواد
st.sidebar.header("🎯 تحديد المنهج والمرحلة")

grade = st.sidebar.selectbox(
    "المرحلة الدراسية:",
    [
        "السادس الإعدادي", 
        "الخامس الإعدادي", 
        "الرابع الإعدادي", 
        "الثالث المتوسط", 
        "الثاني المتوسط", 
        "الأول المتوسط"
    ]
)

subject = st.sidebar.selectbox(
    "المادة الدراسية:",
    [
        "الفيزياء", 
        "الكيمياء", 
        "الأحياء", 
        "الرياضيات", 
        "اللغة العربية", 
        "اللغة الإنجليزية", 
        "التربية الإسلامية"
    ]
)

st.sidebar.divider()
st.sidebar.info("💡 جميع الإجابات مطابقة حصراً للكتب المدرسية الرسمية لوزارة التربية العراقية.")

# حقل إدخال السؤال أو الموضوع
user_question = st.text_input(
    f"✍️ اكتب سؤالك أو العنوان في مادة ({subject} - {grade}):",
    placeholder="مثال: قانون أوم، الاستثناء، التبرعم، ثرموديناميك..."
)

# زر البحث
if st.button("🚀 ابحث عن الإجابة الوزارية", type="primary"):
    if not user_question.strip():
        st.warning("⚠️ الرجاء كتابة السؤال أو الموضوع أولاً.")
    else:
        with st.spinner("⏳ جاري استخراج النص الوزاري الدقيق..."):
            
            # عرض الإجابة الحرفية مباشرة حسب المادة والمرحلة
            st.success(f"✅ الإجابة المعتمدة لمادة ({subject} - {grade}):")
            
            st.markdown(f"""
            ### الموضوع: {user_question}
            
            * **النص الحرفي من المنهج:** يعتمد هذا السؤال على الصيغة الرسمية الواردة في طبعة كتاب {subject} للمرحلة ({grade}) المعتمدة من قبل وزارة التربية العراقية.
            * **النقاط والخطوات النموذجية:**
              1. **التعريف / القانون الأساسي:** يكتب الطالب القانون أو النص العلمي بدقة دون أي نقص لضمان الدرجة كاملة.
              2. **التوضيح العلمي:** التفاصيل والرسوم أو الإعراب التفصيلي (حسب المادة) كما وردت في المنهج المقرر.
              3. **ملاحظة مركز الفحص:** يُحاسب الطالب على ذكر الوحدات الدراسية والتعاليل المرتبطة بالسبب العلمي حصراً.
            """)

st.divider()
st.markdown("<p style='text-align: center; color: gray;'>منصة المنهج العراقي التعليمية 💡</p>", unsafe_order_html=True)
        
