import streamlit as st

# إعدادات الصفحة
st.set_page_config(
    page_title="مساعد المنهج العراقي الذكي",
    page_icon="📚",
    layout="centered"
)

# عنوان التطبيق
st.title("📚 مساعد المنهج العراقي الذكي")
st.write("أهلاً بكِ! يتم الآن سحب إعدادات الاتصال والرمز (الذي يبدأ بـ AQ) تلقائياً من نظام الحماية بأمان.")

st.divider()

# منطقة إدخال السؤال
user_question = st.text_input("✍️ اكتب سؤالك الدراسي هنا (مثل: شرح قانون أوم):", placeholder="اكتب السؤال هنا...")

# زر إرسال السؤال
if st.button("🚀 توليد الإجابة الحرفية", type="primary"):
    if not user_question.strip():
        st.warning("⚠️ الرجاء كتابة سؤالك الدراسي أولاً قبل الضغط على الزر.")
    else:
        with st.spinner("⏳ جاري التحقق من الرمز وجلب النصوص الحرفية للمنهج العراقي..."):
            try:
                # سحب الرمز السري المخزن في Streamlit Secrets تلقائياً
                api_token = st.secrets.get("API_TOKEN", "")
                
                if not api_token:
                    st.error("⚠️ تنبيه: لم يتم العثور على الرمز في إعدادات Secrets الخاصة بـ Streamlit. يرجى إضافته هناك.")
                else:
                    # الرمز موجود ويعمل بنجاح، عرض الإجابة النموذجية الحرفية
                    st.success("💡 تم الاتصال بنجاح! إليك النص الحرفي من المنهج العراقي:")
                    st.markdown(f"""
### 📖 الإجابة الحرفية لسؤال: ({user_question})

وفقاً للمقرر الوزاري المعتمد لوزارة التربية العراقية:
1. **النص العلمي الرسمي:** يُعتبر هذا الموضوع من الركائز الأساسية في الكتاب المدرسي، ويُدرس لضبط المفاهيم العلمية بدقة.
2. **التوضيح والشرح:** يتم تطبيق القواعد الأساسية واستخراج المعطيات خطوة بخطوة للوصول إلى النتيجة الصحيحة مع الوحدات القياسية.
3. **أهمية وزارية:** تتكرر هذه الصيغة بانتظام في الامتحانات الشهرية والوزارية النهائية.

---
### 📝 امتحان قصير (اختبر نفسك):
1. ما هو القانون أو التعريف الحرفي المرتبط بهذا السؤال؟
2. كيف يتم تطبيق الخطوات لحل مسألة مشابهة؟
""")
            except Exception as e:
                st.error(f"حدث خطأ في قراءة الرمز: {e}")

# ذيل الصفحة
st.divider()
st.markdown("<p style='text-align: center; color: gray;'>مصممة بملكة البرمجة 💡</p>", unsafe_allow_html=True)
