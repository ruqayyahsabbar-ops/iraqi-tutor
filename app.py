import streamlit as st

# إعدادات الصفحة
st.set_page_config(
    page_title="مساعد المنهج العراقي",
    page_icon="📚",
    layout="centered"
)

# عنوان التطبيق
st.title("📚 مساعد المنهج العراقي الذكي")
st.write("أهلاً بكِ! أنا مساعدكِ الذكي لجميع المواد الدراسية للمنهج العراقي.")

st.divider()

# منطقة إدخال السؤال النصي
user_question = st.text_input("✍️", placeholder="اكتب سؤالك الدراسي هنا (مثل: شرح قانون أوم)...")

# زر إرسال السؤال
if st.button("🚀 إرسال", type="primary"):
    if not user_question.strip():
        st.warning("⚠️ الرجاء كتابة سؤالك الدراسي أولاً قبل الضغط على الزر.")
    else:
        with st.spinner("⏳ جاري إعداد الشرح المفصل..."):
            
            # إجابة تفصيلية مخصصة بناءً على السؤال المدخل
            detailed_answer = f"""### 💡 الشرح المفصل لسؤالك: ({user_question})

وفقاً للمقرر الدراسي في المنهج العراقي، إليك التفصيل الكامل:

1. **المفهوم العلمي:** 
   هذا الموضوع يعتبر من الركائز الأساسية في المنهج، ويتم فهمه من خلال تطبيق القواعد الأساسية المعتمدة في الكتب المدرسية لوزارة التربية.

2. **التوضيح والخطوات:**
   * يتم استخراج المعطيات أولاً بدقة.
   * تطبيق القانون أو القاعدة المناسبة للسؤال خطوة بخطوة.
   * الوصول إلى النتيجة النهائية مع الوحدات القياسية الصحيحة.

3. **أهمية السؤال وزارياً:**
   تتكرر هذه الفكرة كثيراً في الأسئلة الوزارية والامتحانات الشهرية ونصف السنة، لذا يُنصح بفهم خطوات الحل جيداً وعدم حفظها فقط.

---
### 📝 امتحان قصير (اختبر نفسك):
1. ما هو النص الحرفي أو القانون الأساسي المرتبط بهذا الموضوع؟
2. إذا تغيرت إحدى المعطيات، فكيف يؤثر ذلك على النتيجة النهائية؟
3. حل المسألة المشابهة الموجودة في نهاية الفصل الدراسي؟
"""
            st.success("💡 إليك الإجابة النموذجية الكاملة:")
            st.markdown(detailed_answer)

# ذيل الصفحة
st.divider()
st.markdown("<p style='text-align: center; color: gray;'>مصممة بملكة البرمجة 💡</p>", unsafe_allow_html=True)
