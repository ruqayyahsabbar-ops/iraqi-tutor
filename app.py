import streamlit as st

# إعدادات الصفحة
st.set_page_config(
    page_title="مساعد المنهج العراقي",
    page_icon="📚",
    layout="centered"
)

# عنوان التطبيق
st.title("📚 مساعد المنهج العراقي الذكي")
st.write("أهلاً بك يا بطل! أنا مساعدك الذكي المخصص للإجابة على أسئلة المنهج الدراسي العراقي لجميع المراحل.")

# صندوق إدخال السؤال
st.divider()
user_question = st.text_input("اكتب سؤالك الدراسي هنا:", placeholder="مثلاً: ما هي أهم أحداث ثورة العشرين؟ أو اشرح قانون أوم...")

# زر إرسال السؤال
if st.button("اسأل المساعد", type="primary"):
    if user_question.strip() == "":
        st.warning("الرجاء كتابة سؤالك أولاً قبل الضغط على الزر.")
    else:
        with st.spinner("جاري البحث في المنهج وتحضير الإجابة..."):
            # محاكاة إجابة المساعد (يمكنك لاحقاً ربطها بنموذج ذكاء اصطناعي حقيقي)
            st.success("إليك الإجابة النموذجية:")
            st.markdown(f"""
            بخصوص سؤالك حول: **{user_question}**
            
            وفقاً للمنهج الدراسي المقرر في العراق، فإن الإجابة باختصار تتلخص في النقاط الآتية:
            1. يعتمد فهم هذا الموضوع على المبادئ الأساسية الواردة في الكتاب المدرسي الرسمي.
            2. يُنصح دائماً بمراجعة التمارين والأسئلة الوزارية الخاصة بهذا الفصل لضمان الدرجة الكاملة.
            
            *(هذا نموذج تجريبي جاهز، ويمكننا تطويره لربطه بالذكاء الاصطناعي بشكل كامل ليعطي إجابات مفصلة لكل مادة!)*
            """)

# تذيل الصفحة
st.divider()
st.markdown("<p style='text-align: center; color: gray;'>تم تطوير هذا التطبيق خصيصاً لطلبة العراق 🇮🇶</p>", unsafe_allow_html=True)
